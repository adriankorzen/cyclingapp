CREATE TABLE rider (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   VARCHAR(100)             NOT NULL,
    weight_kg              NUMERIC(5, 2)            NOT NULL,
    ftp_watts              INTEGER,
    lthr_bpm               INTEGER,
    max_heart_rate_bpm     INTEGER,
    resting_heart_rate_bpm INTEGER,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT rider_weight_positive CHECK (weight_kg > 0),
    CONSTRAINT rider_ftp_positive CHECK (ftp_watts > 0),
    CONSTRAINT rider_lthr_positive CHECK (lthr_bpm > 0),
    CONSTRAINT rider_max_hr_positive CHECK (max_heart_rate_bpm > 0),
    CONSTRAINT rider_resting_hr_positive CHECK (resting_heart_rate_bpm > 0)
);
