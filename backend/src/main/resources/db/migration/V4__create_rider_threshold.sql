-- Threshold history: each entry holds the rider's thresholds valid from effective_from until the next entry.
CREATE TABLE rider_threshold (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id           BIGINT                   NOT NULL REFERENCES rider (id) ON DELETE CASCADE,
    effective_from     DATE                     NOT NULL,
    ftp_watts          INTEGER,
    lthr_bpm           INTEGER,
    max_heart_rate_bpm INTEGER,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT rider_threshold_rider_date_unique UNIQUE (rider_id, effective_from),
    CONSTRAINT rider_threshold_ftp_positive CHECK (ftp_watts > 0),
    CONSTRAINT rider_threshold_lthr_positive CHECK (lthr_bpm > 0),
    CONSTRAINT rider_threshold_max_hr_positive CHECK (max_heart_rate_bpm > 0)
);

-- Existing profile thresholds become the first history entry
INSERT INTO rider_threshold (rider_id, effective_from, ftp_watts, lthr_bpm, max_heart_rate_bpm, created_at)
SELECT id, created_at::date, ftp_watts, lthr_bpm, max_heart_rate_bpm, now()
FROM rider
WHERE ftp_watts IS NOT NULL OR lthr_bpm IS NOT NULL OR max_heart_rate_bpm IS NOT NULL;

ALTER TABLE rider
    DROP COLUMN ftp_watts,
    DROP COLUMN lthr_bpm,
    DROP COLUMN max_heart_rate_bpm;
