CREATE TABLE activity (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id                BIGINT                   NOT NULL REFERENCES rider (id) ON DELETE CASCADE,
    source                  VARCHAR(20)              NOT NULL,
    external_id             VARCHAR(64)              NOT NULL,
    name                    VARCHAR(255),
    sport_type              VARCHAR(50),
    start_time              TIMESTAMP WITH TIME ZONE NOT NULL,
    start_time_local        TIMESTAMP,
    duration_seconds        INTEGER,
    moving_duration_seconds INTEGER,
    distance_meters         DOUBLE PRECISION,
    elevation_gain_meters   DOUBLE PRECISION,
    average_heart_rate      INTEGER,
    max_heart_rate          INTEGER,
    average_power           INTEGER,
    max_power               INTEGER,
    normalized_power        INTEGER,
    average_cadence         INTEGER,
    calories                INTEGER,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT activity_rider_source_external_id_unique UNIQUE (rider_id, source, external_id)
);

CREATE INDEX activity_rider_start_time_idx ON activity (rider_id, start_time DESC);

-- Original activity files (e.g. FIT) are kept separately so listing activities never loads them
CREATE TABLE activity_file (
    activity_id BIGINT PRIMARY KEY REFERENCES activity (id) ON DELETE CASCADE,
    format      VARCHAR(10) NOT NULL,
    content     BYTEA       NOT NULL
);
